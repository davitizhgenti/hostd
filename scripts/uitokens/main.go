// Command uitokens writes hostd's design tokens (deploy/files/shell/tokens.toml)
// out for everything that draws:
//
//	deploy/files/shell/qml/Hostd/Theme.qml  the shell's QML singleton, scaled
//	                                         with the screen's height
//	deploy/files/shell/tokens.json          the same values, for anything else
//	docs/stylesheets/tokens.css             CSS custom properties for the docs site
//	deploy/files/sway/config                the fallback background color,
//	                                         between its token markers
//
// Run from the repository's root (go generate ./deploy does). With -check it
// writes nothing and fails if any of them is out of date.
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"

	"github.com/BurntSushi/toml"
)

const source = "deploy/files/shell/tokens.toml"

// units of each group's numbers; a group not listed has plain values.
var units = map[string]string{
	"type": "px", "space": "px", "line": "px", "layout": "px", "motion": "ms",
}

// scaled groups are sizes on a 1080-pixel-high screen: Theme.qml multiplies
// them by its scale.
var scaled = map[string]bool{"type": true, "space": true, "line": true, "layout": true}

// The Sway config's lines between these are generated.
const (
	swayBegin = "# --- design tokens (generated by scripts/uitokens; edit deploy/files/shell/tokens.toml) ---"
	swayEnd   = "# --- end of design tokens ---"
)

func main() { os.Exit(run(os.Args[1:], os.Stderr)) }

func run(args []string, stderr io.Writer) int {
	fs := flag.NewFlagSet("uitokens", flag.ContinueOnError)
	fs.SetOutput(stderr)
	check := fs.Bool("check", false, "write nothing; fail if a generated file is out of date")
	root := fs.String("root", ".", "the repository's root")
	if err := fs.Parse(args); err != nil {
		return 2
	}
	outs, err := generate(*root)
	if err != nil {
		fmt.Fprintln(stderr, "uitokens:", err)
		return 1
	}
	stale := 0
	for _, o := range outs {
		old, _ := os.ReadFile(filepath.Join(*root, o.path))
		if bytes.Equal(old, o.data) {
			continue
		}
		if *check {
			fmt.Fprintf(stderr, "uitokens: %s is out of date: run go generate ./deploy\n", o.path)
			stale++
			continue
		}
		if err := os.WriteFile(filepath.Join(*root, o.path), o.data, 0o644); err != nil {
			fmt.Fprintln(stderr, "uitokens:", err)
			return 1
		}
		fmt.Fprintln(stderr, "wrote", o.path)
	}
	if stale > 0 {
		return 1
	}
	return 0
}

type output struct {
	path string
	data []byte
}

// token is one value, in the order the source has it.
type token struct {
	group, name string
	value       any
}

func (t token) cssName() string { return "--" + t.group + "-" + t.name }

func (t token) cssValue() string {
	switch v := t.value.(type) {
	case int64:
		return fmt.Sprintf("%d%s", v, units[t.group])
	case float64:
		return fmt.Sprintf("%g%s", v, units[t.group])
	default:
		if t.group == "font" {
			return fmt.Sprintf("%q, sans-serif", v)
		}
		return fmt.Sprint(v)
	}
}

// qmlName: safe-margin -> safeMargin.
func qmlName(s string) string {
	parts := strings.Split(s, "-")
	for i := 1; i < len(parts); i++ {
		if parts[i] != "" {
			parts[i] = strings.ToUpper(parts[i][:1]) + parts[i][1:]
		}
	}
	return strings.Join(parts, "")
}

// qmlProperty: one flat, typed property per token (Theme.colorText,
// Theme.layoutSafeMargin), so qmllint checks every use.
func (t token) qmlProperty() string {
	name := qmlName(t.group) + strings.ToUpper(qmlName(t.name)[:1]) + qmlName(t.name)[1:]
	switch v := t.value.(type) {
	case int64, float64:
		if scaled[t.group] {
			return fmt.Sprintf("readonly property int %s: Math.max(1, Math.round(%v * scale))", name, v)
		}
		if t.group == "motion" {
			return fmt.Sprintf("readonly property int %s: Math.round(%v * animate)", name, v)
		}
		if f, ok := v.(float64); ok && f != float64(int64(f)) {
			return fmt.Sprintf("readonly property real %s: %v", name, v) // a share, such as art.dim
		}
		return fmt.Sprintf("readonly property int %s: %v", name, v)
	default:
		s := fmt.Sprint(v)
		if strings.HasPrefix(s, "#") {
			return fmt.Sprintf("readonly property color %s: %q", name, s)
		}
		return fmt.Sprintf("readonly property string %s: %q", name, s)
	}
}

func load(root string) ([]token, error) {
	var raw map[string]map[string]any
	md, err := toml.DecodeFile(filepath.Join(root, source), &raw)
	if err != nil {
		return nil, err
	}
	var out []token
	for _, key := range md.Keys() {
		if len(key) != 2 {
			continue // a group's own key
		}
		v := raw[key[0]][key[1]]
		switch v.(type) {
		case string, int64, float64:
		default:
			return nil, fmt.Errorf("%s.%s: a token is a string or a number", key[0], key[1])
		}
		out = append(out, token{key[0], key[1], v})
	}
	if len(out) == 0 {
		return nil, errors.New(source + " has no tokens")
	}
	return out, nil
}

func generate(root string) ([]output, error) {
	tokens, err := load(root)
	if err != nil {
		return nil, err
	}
	js, err := jsonFile(tokens)
	if err != nil {
		return nil, err
	}
	sway, err := swayConfig(root, tokens)
	if err != nil {
		return nil, err
	}
	return []output{
		{"deploy/files/shell/qml/Hostd/Theme.qml", qmlFile(tokens)},
		{"deploy/files/shell/tokens.json", js},
		{"docs/stylesheets/tokens.css", cssFile(tokens)},
		{"deploy/files/sway/config", sway},
	}, nil
}

// qmlFile: a singleton with every token as a typed property, grouped by
// comments: Theme.colorText, Theme.typeBody, Theme.layoutSafeMargin. The
// shell sets Theme.scale from the screen's height.
func qmlFile(tokens []token) []byte {
	var b bytes.Buffer
	b.WriteString("// hostd's design tokens. Generated by scripts/uitokens from\n" +
		"// deploy/files/shell/tokens.toml: edit that, then go generate ./deploy.\n" +
		"pragma Singleton\nimport QtQuick\n\nQtObject {\n" +
		"    // Sizes are for a 1080-pixel-high screen; the shell sets the scale.\n" +
		"    property real scale: 1.0\n" +
		"    // The screen's width in px, set by the shell: the menu is centred on it.\n" +
		"    property int screenWidth: 1920\n" +
		"    // Every duration is multiplied by this: tests set 0, so nothing moves.\n" +
		"    property real animate: 1.0\n")
	group := ""
	for _, t := range tokens {
		if t.group != group {
			fmt.Fprintf(&b, "\n    // %s\n", t.group)
			group = t.group
		}
		fmt.Fprintf(&b, "    %s\n", t.qmlProperty())
	}
	b.WriteString("}\n")
	return b.Bytes()
}

func cssFile(tokens []token) []byte {
	var b bytes.Buffer
	b.WriteString("/* hostd's design tokens. Generated by scripts/uitokens from\n" +
		"   deploy/files/shell/tokens.toml: edit that, then go generate ./deploy. */\n:root {\n")
	group := ""
	for _, t := range tokens {
		if t.group != group && group != "" {
			b.WriteString("\n")
		}
		group = t.group
		fmt.Fprintf(&b, "  %s: %s;\n", t.cssName(), t.cssValue())
	}
	b.WriteString("}\n")
	return b.Bytes()
}

// jsonFile: {"color": {"bg": "#..."}, "type": {"body": 26}, ...}, with each
// group's unit beside it ("units": {"type": "px"}).
func jsonFile(tokens []token) ([]byte, error) {
	groups := map[string]map[string]any{}
	for _, t := range tokens {
		if groups[t.group] == nil {
			groups[t.group] = map[string]any{}
		}
		groups[t.group][t.name] = t.value
	}
	out := map[string]any{"units": units}
	for g, m := range groups {
		out[g] = m
	}
	b, err := json.MarshalIndent(out, "", "  ")
	return append(b, '\n'), err
}

func value(tokens []token, group, name string) (string, error) {
	for _, t := range tokens {
		if t.group == group && t.name == name {
			return t.cssValue(), nil
		}
	}
	return "", fmt.Errorf("no token %s.%s", group, name)
}

func swayConfig(root string, tokens []token) ([]byte, error) {
	path := filepath.Join(root, "deploy/files/sway/config")
	b, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	bg, err := value(tokens, "color", "bg")
	if err != nil {
		return nil, err
	}
	s := string(b)
	// The begin marker's text names the source, which has moved before: find
	// it by its start.
	i, j := strings.Index(s, "# --- design tokens"), strings.Index(s, swayEnd)
	if i < 0 || j < i {
		return nil, errors.New("deploy/files/sway/config has no design token markers")
	}
	block := swayBegin + "\noutput * bg " + bg + " solid_color\n"
	return []byte(s[:i] + block + s[j:]), nil
}
