// Command uitokens writes hostd's design tokens (deploy/files/ui/tokens.toml)
// out for everything that draws:
//
//	deploy/files/ui/tokens.css   CSS custom properties (the menu and notices, GTK 4.16+)
//	deploy/files/ui/tokens.json  the same values, for anything that is not CSS
//	docs/stylesheets/tokens.css  the docs site's copy
//	deploy/files/sway/config     the background color, between its token markers
//
// Run from the repository's root (go generate ./deploy does). With -check it
// writes nothing and fails if any of them is out of date.
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"

	"github.com/BurntSushi/toml"
)

const source = "deploy/files/ui/tokens.toml"

// units of each group's numbers; a group not listed has plain values.
var units = map[string]string{
	"type": "px", "space": "px", "radius": "px", "line": "px", "layout": "px", "motion": "ms",
}

// The Sway config's lines between these are generated.
const (
	swayBegin = "# --- design tokens (generated by scripts/uitokens; edit deploy/files/ui/tokens.toml) ---"
	swayEnd   = "# --- end of design tokens ---"
)

func main() { os.Exit(run(os.Args[1:], os.Stderr)) }

func run(args []string, stderr io.Writer) int {
	fs := flag.NewFlagSet("uitokens", flag.ContinueOnError)
	fs.SetOutput(stderr)
	check := fs.Bool("check", false, "write nothing; fail if a generated file is out of date")
	root := fs.String("root", ".", "the repository's root")
	if err := fs.Parse(args); err != nil {
		return 2
	}
	outs, err := generate(*root)
	if err != nil {
		fmt.Fprintln(stderr, "uitokens:", err)
		return 1
	}
	stale := 0
	for _, o := range outs {
		old, _ := os.ReadFile(filepath.Join(*root, o.path))
		if bytes.Equal(old, o.data) {
			continue
		}
		if *check {
			fmt.Fprintf(stderr, "uitokens: %s is out of date: run go generate ./deploy\n", o.path)
			stale++
			continue
		}
		if err := os.WriteFile(filepath.Join(*root, o.path), o.data, 0o644); err != nil {
			fmt.Fprintln(stderr, "uitokens:", err)
			return 1
		}
		fmt.Fprintln(stderr, "wrote", o.path)
	}
	if stale > 0 {
		return 1
	}
	return 0
}

type output struct {
	path string
	data []byte
}

// token is one value, in the order the source has it.
type token struct {
	group, name string
	value       any
}

func (t token) cssName() string { return "--" + t.group + "-" + t.name }

func (t token) cssValue() string {
	switch v := t.value.(type) {
	case int64:
		return fmt.Sprintf("%d%s", v, units[t.group])
	case float64:
		return fmt.Sprintf("%g%s", v, units[t.group])
	default:
		return fmt.Sprint(v)
	}
}

func load(root string) ([]token, error) {
	var raw map[string]map[string]any
	md, err := toml.DecodeFile(filepath.Join(root, source), &raw)
	if err != nil {
		return nil, err
	}
	var out []token
	for _, key := range md.Keys() {
		if len(key) != 2 {
			continue // a group's own key
		}
		v := raw[key[0]][key[1]]
		switch v.(type) {
		case string, int64, float64:
		default:
			return nil, fmt.Errorf("%s.%s: a token is a string or a number", key[0], key[1])
		}
		out = append(out, token{key[0], key[1], v})
	}
	if len(out) == 0 {
		return nil, errors.New(source + " has no tokens")
	}
	return out, nil
}

func generate(root string) ([]output, error) {
	tokens, err := load(root)
	if err != nil {
		return nil, err
	}
	css := cssFile(tokens)
	js, err := jsonFile(tokens)
	if err != nil {
		return nil, err
	}
	sway, err := swayConfig(root, tokens)
	if err != nil {
		return nil, err
	}
	return []output{
		{"deploy/files/ui/tokens.css", css},
		{"deploy/files/ui/tokens.json", js},
		{"docs/stylesheets/tokens.css", css},
		{"deploy/files/sway/config", sway},
	}, nil
}

func cssFile(tokens []token) []byte {
	var b bytes.Buffer
	b.WriteString("/* hostd's design tokens. Generated by scripts/uitokens from\n" +
		"   deploy/files/ui/tokens.toml: edit that, then go generate ./deploy. */\n:root {\n")
	group := ""
	for _, t := range tokens {
		if t.group != group && group != "" {
			b.WriteString("\n")
		}
		group = t.group
		fmt.Fprintf(&b, "  %s: %s;\n", t.cssName(), t.cssValue())
	}
	b.WriteString("}\n")
	return b.Bytes()
}

// jsonFile: {"color": {"bg": "#..."}, "type": {"body": 27}, ...}, with each
// group's unit beside it ("units": {"type": "px"}).
func jsonFile(tokens []token) ([]byte, error) {
	groups := map[string]map[string]any{}
	for _, t := range tokens {
		if groups[t.group] == nil {
			groups[t.group] = map[string]any{}
		}
		groups[t.group][t.name] = t.value
	}
	out := map[string]any{"units": units}
	for g, m := range groups {
		out[g] = m
	}
	b, err := json.MarshalIndent(out, "", "  ")
	return append(b, '\n'), err
}

func value(tokens []token, group, name string) (string, error) {
	for _, t := range tokens {
		if t.group == group && t.name == name {
			return t.cssValue(), nil
		}
	}
	return "", fmt.Errorf("no token %s.%s", group, name)
}

func swayConfig(root string, tokens []token) ([]byte, error) {
	path := filepath.Join(root, "deploy/files/sway/config")
	b, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	bg, err := value(tokens, "color", "bg")
	if err != nil {
		return nil, err
	}
	s := string(b)
	i, j := strings.Index(s, swayBegin), strings.Index(s, swayEnd)
	if i < 0 || j < i {
		return nil, errors.New("deploy/files/sway/config has no design token markers")
	}
	block := swayBegin + "\noutput * bg " + bg + " solid_color\n"
	return []byte(s[:i] + block + s[j:]), nil
}
